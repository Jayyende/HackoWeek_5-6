# dot_product.py

import numpy as np

print("=== DOT PRODUCT ===\n")

A = np.array([1, 2, 3])
B = np.array([4, 5, 6])

print("Vector A:", A)
print("Vector B:", B)

dot = np.dot(A, B)

print("\nDot Product:")
print(dot)

print("\nInterpretation:")
print("A higher value generally indicates greater similarity.")

print("\n=== PROGRAM COMPLETED ===")
